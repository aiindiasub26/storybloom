// Build step.
//   node scripts/build.mjs                  → Netlify (unscrolled.me): writes site/app/js/pass-key.js with the
//                                             PUBLIC half of PASS_PRIVATE_JWK and regenerates site/app/sw.js
//   node scripts/build.mjs --family <dir>   → GitHub Pages family copy: copies site/app to <dir>, always unlocked
//                                             (no code needed), with its own offline file list
import { readFileSync, writeFileSync, readdirSync, statSync, cpSync, rmSync } from "node:fs";
import { createHash } from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const source = path.join(here, "..", "site", "app");
const famIdx = process.argv.indexOf("--family");
const family = famIdx > -1;
const app = family ? path.resolve(process.argv[famIdx + 1] || "family") : source;

if (family) {
  rmSync(app, { recursive: true, force: true });
  cpSync(source, app, { recursive: true });
  writeFileSync(path.join(app, "js", "pass-key.js"), "/* generated by scripts/build.mjs: family copy, always unlocked */\nwindow.SB_FREE = true;\nwindow.SB_PASS_KEY = null;\n");
} else {
  let pub = null;
  try {
    const j = JSON.parse(process.env.PASS_PRIVATE_JWK || "");
    if (j.kty === "EC" && j.x && j.y) pub = { kty: j.kty, crv: j.crv, x: j.x, y: j.y };
  } catch {}
  if (!pub) console.warn("⚠  PASS_PRIVATE_JWK is not set: the app will show 'getting ready' until it is. See SETUP.md.");
  writeFileSync(path.join(app, "js", "pass-key.js"), "/* generated by scripts/build.mjs */\nwindow.SB_PASS_KEY = " + JSON.stringify(pub) + ";\n");
}

const files = ["./", "index.html", "manifest.webmanifest"];
const hash = createHash("md5");
function walk(dir) {
  for (const name of readdirSync(path.join(app, dir)).sort()) {
    const rel = dir + "/" + name;
    if (statSync(path.join(app, rel)).isDirectory()) walk(rel);
    else { files.push(rel); hash.update(rel); hash.update(readFileSync(path.join(app, rel))); }
  }
}
["css", "js", "assets"].forEach(walk);
hash.update(readFileSync(path.join(app, "index.html")));
const version = hash.digest("hex").slice(0, 10);
const sw = readFileSync(path.join(here, "sw.template.js"), "utf8")
  .replace("__VERSION__", version)
  .replace("__FILES__", JSON.stringify([...new Set(files)].sort()));
writeFileSync(path.join(app, "sw.js"), sw);
console.log(`${family ? "family copy → " + app : "unscrolled.me"} · sw.js ${version} · ${files.length} files`);
