// Netlify build step (also run by `npm run dev`):
//  1. writes site/app/js/pass-key.js with the PUBLIC half of PASS_PRIVATE_JWK, so the app can check passes offline
//  2. regenerates site/app/sw.js with every file the app needs offline
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { createHash } from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const app = path.join(here, "..", "site", "app");

let pub = null;
try {
  const j = JSON.parse(process.env.PASS_PRIVATE_JWK || "");
  if (j.kty === "EC" && j.x && j.y) pub = { kty: j.kty, crv: j.crv, x: j.x, y: j.y };
} catch {}
if (!pub) console.warn("⚠  PASS_PRIVATE_JWK is not set: the app will show 'getting ready' until it is. See SETUP.md.");
writeFileSync(path.join(app, "js", "pass-key.js"), "/* generated by scripts/build.mjs */\nwindow.SB_PASS_KEY = " + JSON.stringify(pub) + ";\n");

const files = ["./", "index.html", "manifest.webmanifest"];
const hash = createHash("md5");
function walk(dir) {
  for (const name of readdirSync(path.join(app, dir)).sort()) {
    const rel = dir + "/" + name;
    if (statSync(path.join(app, rel)).isDirectory()) walk(rel);
    else { files.push(rel); hash.update(rel); hash.update(readFileSync(path.join(app, rel))); }
  }
}
["css", "js", "assets"].forEach(walk);
hash.update(readFileSync(path.join(app, "index.html")));
const version = hash.digest("hex").slice(0, 10);
const sw = readFileSync(path.join(here, "sw.template.js"), "utf8")
  .replace("__VERSION__", version)
  .replace("__FILES__", JSON.stringify([...new Set(files)].sort()));
writeFileSync(path.join(app, "sw.js"), sw);
console.log(`sw.js ${version} · ${files.length} files · pass key ${pub ? "set" : "MISSING"}`);
